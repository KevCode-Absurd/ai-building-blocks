import fs from 'node:fs/promises';import assert from 'node:assert/strict';import{installDither}from'../src/lib/pixel.ts';
// Use the original pixel generator at build time. The browser receives the
// exact masks as CSS instead of rebuilding every SVG during application boot.
const masks=new Map();installDither({style:{setProperty:(name,value)=>{assert(/^--(?:dither|pat)-[a-z0-9-]+$/.test(name));assert(!masks.has(name));masks.set(name,value);}}});
for(const key of ['--dither-x','--dither-y','--dither-corner'])assert(masks.has(key));assert(masks.size>40);
// The three edge masks are small and used on the first screen, so they stay inline. Each card pattern
// (only drawn on cards) becomes its own small file that Vite hashes into /assets: the render-blocking
// stylesheet carries a short address instead of about 4 KB per pattern.
const dir=new URL('../src/patterns/',import.meta.url);await fs.mkdir(dir,{recursive:true});
const inline=[],files=new Map();
for(const[name,value]of masks){
  if(!name.startsWith('--pat-')){inline.push(name+':'+value+';');continue;}
  const m=/^url\("data:image\/svg\+xml,(.*)"\)$/.exec(value);assert(m,'pattern is an inline SVG: '+name);
  const file=name.slice(6)+'.svg';files.set(file,decodeURIComponent(m[1])+'\n');
  inline.push(name+':url("./patterns/'+file+'");');
}
for(const[file,svg]of files){const at=new URL(file,dir);if(await fs.readFile(at,'utf8').catch(()=>null)!==svg)await fs.writeFile(at,svg);}
for(const old of await fs.readdir(dir))if(old.endsWith('.svg')&&!files.has(old))await fs.rm(new URL(old,dir));
// Zero specificity keeps these defaults overridable. The critical hero already
// has its own exact mask; card patterns do not belong in first-screen HTML.
const css='/* Generated by scripts/build-dither-css.mjs from lib/pixel.ts. */\n:where(:root){\n'+inline.join('\n')+'\n}\n';
const file=new URL('../src/dither-masks.css',import.meta.url);if(await fs.readFile(file,'utf8').catch(()=>null)!==css)await fs.writeFile(file,css);
console.log(JSON.stringify({ditherMasks:masks.size,patternFiles:files.size,bytes:Buffer.byteLength(css),runtimeSvgGeneration:false}));
