// Turns the world map (Natural Earth land, via world-atlas) into a 1-degree land grid for the hero globe.
// Run once when the map should change: node scripts/make-landmask.mjs  → writes src/landmask.ts
// Row 0 is 89.5°N, column 0 is 179.5°W; one bit per cell, 1 = land.
import fs from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";
import { geoContains } from "d3-geo";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);
const W = 360, H = 180;
const bits = new Uint8Array((W * H) / 8);
let count = 0;
for (let r = 0; r < H; r++) {
  for (let c = 0; c < W; c++) {
    if (geoContains(land, [c - 179.5, 89.5 - r])) { const i = r * W + c; bits[i >> 3] |= 1 << (i & 7); count++; }
  }
}
const b64 = Buffer.from(bits).toString("base64");
const out = `// Generated by scripts/make-landmask.mjs from Natural Earth land (public domain, via world-atlas). Do not edit.
// ${W} x ${H} cells of 1 degree; row 0 is 89.5°N, column 0 is 179.5°W; one bit per cell, 1 = land.
export const LAND_W = ${W};
export const LAND_H = ${H};
export const LAND = "${b64}";
`;
fs.writeFileSync(new URL("../src/landmask.ts", import.meta.url), out);
console.log(`land cells: ${count} of ${W * H} (${((100 * count) / (W * H)).toFixed(1)}%), ${b64.length} characters`);
