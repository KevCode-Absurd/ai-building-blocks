/** The icon as inline SVG, or "" when there is none for this name. */
export function pixelIcon(name, cls = "px-ico") {
  const rows = ICONS[name];
  if (!rows) return "";
  const cells = rows.flatMap((row, y) => [...row].map((c, x) => (c === "." ? "" : `<rect x="${x * 3}" y="${y * 3}" width="2.6" height="2.6"${c === "+" ? ' opacity=".3"' : ""}/>`))).join("");
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true" focusable="false">${cells}</svg>`;
}

