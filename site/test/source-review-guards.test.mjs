const method = '# Synthetic fixture\n\nRead the supplied markdown file of raw notes.\nWrite a checked draft from those notes.\n';
const item = { slug: 'fixture', inputs: [{ type: 'document', required: true }], outputs: [{ type: 'copy_draft', required: true }] };
const inputReview = () => ({ method_sha256: digest(methodBody(method)), inputs: item.inputs, evidence: [{ type: 'document', quote: 'Read the supplied markdown file of raw notes.', rationale: 'The method reads the user-owned notes file, rather than somebody else’s source article.' }] });
test('input evidence supports a reviewed synonym without demanding the literal type token', () => {
  assert.deepEqual(checkInputContract(item, method, inputReview()), []);
});
test('unsupported new types and requiredness changes cannot inherit an older review', () => {
  const changed = { ...item, inputs: [...item.inputs, { type: 'source_text', required: true }] };
  assert.match(checkInputContract(changed, method, inputReview()).join('\n'), /types or requiredness changed/);
  assert.match(checkInputContract(changed, method, inputReview()).join('\n'), /source_text: reviewed evidence missing/);
  assert.match(checkInputContract({ ...item, inputs: [{ type: 'document', required: false }] }, method, inputReview()).join('\n'), /requiredness changed/);
});
test('generated sections and front matter cannot act as input evidence', () => {
  const quote = 'An external source article is required.';
  for (const hidden of [`---\ndescription: ${quote}\n---\n`, `<!-- needs: generated by a fixture -->\n${quote}\n<!-- /needs -->\n`, `<!-- next -->\n${quote}\n<!-- /next -->\n`]) {
    const text = hidden + method, record = { ...inputReview(), method_sha256: digest(methodBody(text)), evidence: [{ type: 'document', quote, rationale: 'This misleading statement exists only in generated material, so it must not count.' }] };
    assert.match(checkInputContract(item, text, record).join('\n'), /exact method quote missing/);
  }
  assert.throws(() => methodBody('<!-- needs: broken -->\nOnly generated claims.'), /unclosed generated/);
});
test('method drift invalidates a review while regeneration and EOL changes do not', () => {
  assert.match(checkInputContract(item, method + '\nRead an extra dataset.', inputReview()).join('\n'), /Method changed/);
  assert.deepEqual(checkInputContract(item, '<!-- needs: rebuilt -->\nChanged generated wording.\n<!-- /needs -->\n' + method.replaceAll('\n', '\r\n'), inputReview()), []);
});
const consumer = { slug: 'checker', inputs: [{ type: 'copy_draft', required: true }], outputs: [{ type: 'audit_report', required: true }] };
const consumerMethod = '# Synthetic checker\nRead the supplied draft and check each claim against its source.\n';
function handoffReview(from = item, to = consumer) {
  return { from_sha256: digest(methodBody(method)), to_sha256: digest(methodBody(consumerMethod)), ports_sha256: digest(JSON.stringify({ outputs: ports(from.outputs), inputs: ports(to.inputs) })), type: 'copy_draft', output_quote: 'Write a checked draft from those notes.', input_quote: 'Read the supplied draft and check each claim against its source.', rationale: 'The producer writes the same draft that the checker reads; source evidence still must be available.' };
}
test('reviewed handoffs require real ports, exact method evidence and fresh contracts', () => {
  assert.deepEqual(checkHandoff(item, consumer, method, consumerMethod, handoffReview()), []);
  assert.match(checkHandoff(item, consumer, method + '\nChanged.', consumerMethod, handoffReview()).join('\n'), /method changed/);
  assert.match(checkHandoff(item, { ...consumer, inputs: [{ type: 'dataset' }] }, method, consumerMethod, handoffReview()).join('\n'), /contract changed/);
  assert.match(checkHandoff(item, consumer, method, consumerMethod, { ...handoffReview(), type: 'dataset' }).join('\n'), /actual output and input/);
});
test('optional outputs need an explicit condition, including adapted handoffs', () => {
  const optional = { ...item, outputs: [{ type: 'copy_draft', required: false }] }, record = handoffReview(optional);
  assert.match(checkHandoff(optional, consumer, method, consumerMethod, record).join('\n'), /optional result/);
  assert.deepEqual(checkHandoff(optional, consumer, method, consumerMethod, { ...record, condition: 'Only use this handoff after the requested draft was actually made and checked.' }), []);
  const adapted = { ...record, type: undefined, from_type: 'copy_draft', to_type: 'copy_draft', adaptation: 'Carry the actual produced draft into the checker, retaining the source references.' };
  assert.match(checkHandoff(optional, consumer, method, consumerMethod, adapted).join('\n'), /optional result/);
  assert.match(checkHandoff(item, consumer, method, consumerMethod, { ...handoffReview(), type: undefined, adaptation: 'A vague bridge with no actual port identifiers is insufficient.' }).join('\n'), /actual output and input/);
});
test('new page-level handoffs require evidence and legacy coverage stays explicit', () => {
  const file = 'catalogue-items/general/fixture/item.yaml', other = 'catalogue-items/general/checker/item.yaml', page = file.replace('item.yaml', 'page.yaml');
  const items = new Map([[file, { ...item, reviewLinkDefinitions: [{ file: page, field: 'next', targets: ['checker'] }] }], [other, consumer]]), methods = new Map([[file, method], [other, consumerMethod]]), registry = { schema: 'abb-source-review/1', inputs: {}, handoffs: {} };
  const legacy = reviewCatalogue({ items, methods, registry });
  assert.deepEqual(legacy.failures, []); assert.equal(legacy.legacyLinksWithoutEvidence, 1); assert.equal(legacy.reviewedLinks, 0);
  const changed = reviewCatalogue({ items, methods, registry, changes: [{ file: page, before: {}, after: { next: ['checker'] } }] });
  assert.match(changed.failures.map(row => row.message).join('\n'), /evidence is missing/);
  const reviewed = reviewCatalogue({ items, methods, registry: { ...registry, handoffs: { [`${page}#next#checker`]: handoffReview() } } });
  assert.deepEqual(reviewed.failures, []); assert.equal(reviewed.reviewedLinks, 1);
});
test('YAML, front matter and colon-shaped text errors report locations without quoting private values', () => {
  const check = (file, text) => checkTextChange({ file, after: Buffer.from(text) });
  assert.match(check('catalogue-items/general/fixture/page.yaml', 'when:\n  - Topic: private fixture value\n').join('\n'), /quote a bullet/);
  const errors = check('catalogue-items/general/fixture/item.yaml', 'name: A fixture: private fixture value\n');
  assert.ok(errors.length); assert.doesNotMatch(errors.join('\n'), /private fixture value/);
  assert.match(check('fixture/SKILL.md', '---\nname: fixture\n').join('\n'), /closing delimiter/);
  assert.deepEqual(check('fixture/SKILL.md', '---\nname: fixture\ndescription: "Text: quoted correctly"\n---\n# Fixture\n'), []);
  const aliases = 'a: &a [x,x,x,x,x,x,x,x,x,x]\nb: &b [' + Array(20).fill('*a').join(',') + ']\nc: [' + Array(20).fill('*b').join(',') + ']\n';
  assert.match(check('fixture.yaml', aliases).join('\n'), /excessive YAML aliases/);
});
