// Deploy a reviewed Worker-only delta; preserve assets, secrets and all bindings.
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
const [environment, input, expectedVersion] = process.argv.slice(2);
assert(['staging', 'production'].includes(environment));
const allowed = path.resolve('C:/Users/kevin/.codex/visualizations/2026/10/22/01a161bf-0b97-7cf2-97f3-74eb6d30d1e4');
const worker = path.resolve(input || '');
assert(worker.startsWith(allowed + path.sep) && path.basename(worker) === 'worker.js');
const release = JSON.parse(await fs.readFile('reports/cloudflare-live-release.json', 'utf8'));
assert.equal(release[environment].versionId, expectedVersion, 'Review the current release before deployment.');
const account = '31c814d2c58a11163d3187f505f0b9c5';
const script = environment === 'staging' ? 'ai-building-blocks-staging' : 'ai-building-blocks';
const privateConfig = await fs.readFile(path.join(process.env.APPDATA, 'xdg.config/.wrangler/config/default.toml'), 'utf8');
const token = privateConfig.match(/^oauth_token\s*=\s*"([^"\r\n]+)"/m)?.[1];
assert(token, 'Wrangler authorization is unavailable.');
async function api(route, init = {}) {
  const response = await fetch(`https://api.cloudflare.com/client/v4/accounts/${account}/workers/scripts/${script}${route}`, { ...init, headers: { authorization: 'Bearer ' + token, ...init.headers }, signal: AbortSignal.timeout(60000) });
  const body = await response.json();
  if (!response.ok || !body.success) throw Error(JSON.stringify({ status: response.status, errors: body.errors?.map(({ code, message }) => ({ code, message })) }));
  return body.result;
}
const canonical = value => Array.isArray(value) ? value.map(canonical) : value && typeof value === 'object' ? Object.fromEntries(Object.keys(value).sort().map(key => [key, canonical(value[key])])) : value;
const sha = value => crypto.createHash('sha256').update(value).digest('hex');
const fingerprint = value => sha(JSON.stringify(canonical(value)) ?? 'null');
const bindingHash = settings => fingerprint([...settings.bindings].sort((a, b) => a.name.localeCompare(b.name)));
const deployments = await api('/deployments');
const previous = (deployments.deployments || deployments)[0];
assert.equal(previous.versions.length, 1);
assert.equal(previous.versions[0].version_id, expectedVersion, 'Remote version changed; stop and review.');
assert.equal(previous.versions[0].percentage, 100);
const before = await api('/settings');
const names = before.bindings.map(binding => binding.name);
for (const name of ['ASSETS', 'COMMENTS', 'SPACES', 'COMPOSER', 'API_READ_LIMITER', 'API_WRITE_LIMITER', 'AI_LIMITER', 'TURNSTILE_SITE_KEY', 'TURNSTILE_SECRET_KEY', 'CLERK_SECRET_KEY']) assert(names.includes(name), 'Missing required binding: ' + name);
if (environment === 'staging') for (const name of ['PREVIEW_PROTECTED', 'PREVIEW_ACCESS_TOKEN']) assert(names.includes(name));
assert.equal(before.bindings.find(binding => binding.name === 'WORKFLOW_COMPOSER_ENABLED')?.text, 'false');
const code = await fs.readFile(worker);
assert(code.length > 100000 && code.length < 2000000, 'Expected a complete reviewed Worker bundle.');
const form = new FormData();
form.set('metadata', JSON.stringify({ main_module: 'worker.js', keep_assets: true, bindings: names.map(name => ({ name, type: 'inherit' })), compatibility_date: before.compatibility_date, compatibility_flags: before.compatibility_flags, annotations: { 'workers/message': 'Reviewed native preview login correction and existing planner fix; retain frozen launch assets' } }));
form.set('worker.js', new Blob([code], { type: 'application/javascript+module' }), 'worker.js');
await api('?bindings_inherit=strict', { method: 'PUT', body: form });
const after = await api('/settings');
assert.equal(bindingHash(after), bindingHash(before), 'Worker bindings changed unexpectedly.');
assert.equal(fingerprint(after.assets), fingerprint(before.assets), 'Asset configuration changed unexpectedly.');
const current = await api('/deployments');
const latest = (current.deployments || current)[0];
assert.equal(latest.versions.length, 1);
assert.equal(latest.versions[0].percentage, 100);
const versionId = latest.versions[0].version_id;
assert.notEqual(versionId, expectedVersion);
const report = { checkedOn: new Date().toISOString(), environment, script, previousVersion: expectedVersion, versionId, workerSha256: sha(code), assetsRetained: true, bindingNamesPreserved: names.length, assetConfigPreserved: true, paidAIEnabled: false, publicRoutesChanged: false };
await fs.writeFile(`reports/cloudflare-${environment}-worker-delta.json`, JSON.stringify(report, null, 2) + '\n');
Object.assign(release[environment], { previousVersionId: expectedVersion, versionId, workerSha256: report.workerSha256, status: 'reviewed Worker-only delta deployed; live delta checks pending' });
if (environment === 'staging') release.staging.verified = false;
release.checkedOn = report.checkedOn;
await fs.writeFile('reports/cloudflare-live-release.json', JSON.stringify(release, null, 2) + '\n');
console.log(JSON.stringify(report, null, 2));
